// ==========================
// ELEMENTS
// ==========================

const audio = document.getElementById("audio");

const cover = document.querySelector(".player-cover");

const title = document.querySelector(
  ".player-song-info h3"
);

const artist = document.querySelector(
  ".player-song-info p"
);

const playBtn = document.querySelector(
  ".main-play-button"
);

const prevBtn = document.querySelector(
  ".previous-button"
);

const nextBtn = document.querySelector(
  ".next-button"
);

const shuffleBtn = document.querySelector(
  ".shuffle-button"
);

const progressBar = document.querySelector(
  ".progress-bar"
);

const volumeSlider = document.querySelector(
  ".volume-slider"
);

const currentTimeEl = document.querySelector(
  ".current-time"
);

const totalTimeEl = document.querySelector(
  ".total-time"
);

// ==========================
// STATE
// ==========================

let currentSong = 0;
let isPlaying = false;
let shuffleMode = true;

// Daftar lagu yang belum diputar
let remainingSongs = [];

// Riwayat lagu saat shuffle aktif
let playHistory = [0];
let historyPosition = 0;

// ==========================
// FORMAT TIME
// ==========================

function formatTime(seconds) {

  if (isNaN(seconds)) return "0:00";

  const mins = Math.floor(seconds / 60);

  const secs = Math.floor(seconds % 60)
    .toString()
    .padStart(2, "0");

  return `${mins}:${secs}`;
}

// ==========================
// LOAD SONG
// ==========================

function loadSong(index) {

  const song = playlist[index];

  audio.src = song.src;

  cover.src = song.cover;

  title.textContent = song.title;

  artist.textContent = song.artist;
}

// ==========================
// PLAY
// ==========================

function playSong() {

  audio.play();

  isPlaying = true;

  playBtn.innerHTML = "❚❚";

  document.title = `Habibie | ${playlist [currentSong].title}`;

}

// ==========================
// PAUSE
// ==========================

function pauseSong() {

  audio.pause();

  isPlaying = false;

  playBtn.innerHTML = "▶";
}

// ==========================
// TOGGLE
// ==========================

playBtn.addEventListener("click", () => {

  if (isPlaying) {
    pauseSong();
  } else {
    playSong();
  }

});


/* ==========================
   SHUFFLE BAG
========================== */

function refillShuffleBag() {
  remainingSongs = playlist
    .map((_, index) => index)
    .filter(index => index !== currentSong);

  // Acak urutan lagu
  for (let i = remainingSongs.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));

    [remainingSongs[i], remainingSongs[j]] =
      [remainingSongs[j], remainingSongs[i]];
  }
}

/* ==========================
   NEXT
========================== */

function nextSong() {
  if (shuffleMode) {
    // Kalau user menekan Previous sebelumnya,
    // lanjutkan riwayat yang sudah ada dahulu.
    if (historyPosition < playHistory.length - 1) {
      historyPosition++;
      currentSong = playHistory[historyPosition];
    } else {
      // Isi ulang hanya ketika semua lagu habis.
      if (remainingSongs.length === 0) {
        refillShuffleBag();
      }

      currentSong = remainingSongs.pop();

      playHistory.push(currentSong);
      historyPosition = playHistory.length - 1;
    }
  } else {
    // Mode normal: urutan playlist
    currentSong = (currentSong + 1) % playlist.length;
  }

  loadSong(currentSong);
  playSong();
}

/* ==========================
   PREVIOUS
========================== */

function previousSong() {
  if (shuffleMode && historyPosition > 0) {
    historyPosition--;
    currentSong = playHistory[historyPosition];
  } else if (!shuffleMode) {
    currentSong =
      (currentSong - 1 + playlist.length) % playlist.length;
  }

  loadSong(currentSong);
  playSong();
}


// ==========================
// BUTTON EVENTS
// ==========================

nextBtn.addEventListener(
  "click",
  nextSong
);

prevBtn.addEventListener(
  "click",
  previousSong
);

// ==========================
// SHUFFLE
// ==========================

shuffleBtn.addEventListener("click", () => {
  shuffleMode = !shuffleMode;

  shuffleBtn.style.opacity =
    shuffleMode ? "1" : "0.5";

  // Mulai putaran shuffle baru dari lagu saat ini.
  if (shuffleMode) {
    playHistory = [currentSong];
    historyPosition = 0;
    refillShuffleBag();
  } else {
    remainingSongs = [];
    playHistory = [currentSong];
    historyPosition = 0;
  }
});

// ==========================
// UPDATE PROGRESS
// ==========================

audio.addEventListener(
  "timeupdate",
  () => {

    const progress =
      (audio.currentTime /
        audio.duration) *
      100;

    progressBar.value =
      progress || 0;

    currentTimeEl.textContent =
      formatTime(
        audio.currentTime
      );

  }
);

// ==========================
// DURATION
// ==========================

audio.addEventListener(
  "loadedmetadata",
  () => {

    totalTimeEl.textContent =
      formatTime(audio.duration);

  }
);

// ==========================
// SEEK
// ==========================

progressBar.addEventListener(
  "input",
  () => {

    const seekTime =
      (progressBar.value / 100) *
      audio.duration;

    audio.currentTime = seekTime;

  }
);

// ==========================
// VOLUME
// ==========================

volumeSlider.addEventListener(
  "input",
  () => {

    audio.volume =
      volumeSlider.value / 100;

  }
);

// ==========================
// SONG ENDED
// ==========================

audio.addEventListener(
  "ended",
  nextSong
);

// ==========================
// INITIAL
// ==========================

audio.volume = 0.7;

volumeSlider.value = 70;

loadSong(currentSong);